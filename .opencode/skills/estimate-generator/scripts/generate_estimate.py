def build_capacity(wb, cfg):
    ws = wb.create_sheet("Capacity Model")
    ws.sheet_view.showGridLines = False

    ws.merge_cells("A1:E1")
    c = ws["A1"]
    c.value = "Team Capacity Model"
    c.fill      = _fill(DARK_BLUE)
    c.font      = _font(bold=True, color=WHITE, size=13)
    c.alignment = _align(h="left", v="center")
    ws.row_dimensions[1].height = 28

    gross    = cfg["sprint_length_days"] * cfg["hours_per_day"]
    overhead = round(gross * cfg["overhead_pct"] / 100)
    eff      = gross - overhead
    usable   = round(eff * 0.90)

    headers = ["Role", "Headcount", "Gross h/sprint", "Ceremony h", "Effective h", "Usable h", "Team Capacity h"]
    for col, h in enumerate(headers, start=1):
        c = ws.cell(row=2, column=col, value=h)
        style_header(c)

    team = cfg.get("team", {})
    row = 3
    team_total = 0
    for role, count in team.items():
        bg = ALT_ROW if row % 2 == 0 else WHITE
        team_cap = usable * count
        team_total += team_cap
        vals = [role, count, gross * count, overhead * count,
                eff * count, usable * count, team_cap]
        bolds = [True, False, False, False, False, True, True]
        for col, (v, bo) in enumerate(zip(vals, bolds), start=1):
            style_cell(ws.cell(row=row, column=col, value=v),
                       bg=bg, bold=bo, align="center" if col > 1 else "left")
        row += 1

    # Team total row
    ws.merge_cells(f"A{row}:B{row}")
    c = ws.cell(row=row, column=1, value="TOTAL TEAM CAPACITY / SPRINT")
    c.fill = _fill(MID_BLUE); c.font = _font(bold=True, color=WHITE)
    c.alignment = _align(h="right"); c.border = _border()
    for col in range(3, 7):
        ws.cell(row=row, column=col).fill = _fill(MID_BLUE)
        ws.cell(row=row, column=col).border = _border()
    c = ws.cell(row=row, column=7, value=team_total)
    c.fill = _fill(MID_BLUE); c.font = _font(bold=True, color=WHITE)
