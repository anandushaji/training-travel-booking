# ── Style helpers ─────────────────────────────────────────────────

def _fill(hex_color):
    return PatternFill(fill_type="solid", fgColor=hex_color)

def _font(bold=False, color=DARK_TEXT, size=10, italic=False):
    return Font(bold=bold, color=color, size=size, italic=italic, name="Calibri")

def _align(h="left", v="center", wrap=False):
    return Alignment(horizontal=h, vertical=v, wrap_text=wrap)

def _border(style="thin"):
    s = Side(style=style, color="CCCCCC")
    return Border(left=s, right=s, top=s, bottom=s)

def _thick_bottom():
    thick = Side(style="medium", color=MID_BLUE)
    thin  = Side(style="thin",   color="CCCCCC")
    return Border(left=thin, right=thin, top=thin, bottom=thick)

def style_header(cell, bg=MID_BLUE, fg=HEADER_FG, size=10, align="center"):
    cell.fill      = _fill(bg)
    cell.font      = _font(bold=True, color=fg, size=size)
    cell.alignment = _align(h=align, v="center")
    cell.border    = _border()

def style_cell(cell, bg=WHITE, bold=False, color=DARK_TEXT,
               align="left", wrap=False, italic=False):
    cell.fill      = _fill(bg)
    cell.font      = _font(bold=bold, color=color, italic=italic)
    cell.alignment = _align(h=align, v="center", wrap=wrap)
    cell.border    = _border()

def set_col_width(ws, col, width):
    ws.column_dimensions[get_column_letter(col)].width = width

# ── PERT calculation ─────────────────────────────────────────────

def pert(o, m, p):
    return round((o + 4 * m + p) / 6, 1)

def variance(o, p):
    return round(((p - o) / 6) ** 2, 2)

def risk_color(risk_level):
    r = risk_level.strip().lower()
    if r == "critical": return RISK_CRIT
    if r == "high":     return RISK_HIGH
    if r == "medium":   return RISK_MED
    return RISK_LOW

# ── Working-day calendar ─────────────────────────────────────────

def add_working_days(start: date, days: int) -> date:
    """Add `days` working days (Mon–Fri) to `start`."""
    current = start
    added = 0
    while added < days:
        current += timedelta(days=1)
        if current.weekday() < 5:   # 0=Mon … 4=Fri
            added += 1
    return current

def sprint_dates(start: date, sprint_num: int, sprint_days: int):
    """Return (sprint_start, sprint_end) for sprint_num (1-based)."""
    offset_days = (sprint_num - 1) * sprint_days
    sp_start = add_working_days(start, offset_days) if offset_days > 0 else start
    sp_end   = add_working_days(sp_start, sprint_days - 1)
    return sp_start, sp_end

