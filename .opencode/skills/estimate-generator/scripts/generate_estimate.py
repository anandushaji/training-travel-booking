def build_assumptions(wb, cfg):
    ws = wb.active
    ws.title = "Assumptions"
    ws.sheet_view.showGridLines = False

    # Title
    ws.merge_cells("A1:D1")
    c = ws["A1"]
    c.value = f"{cfg['project_name']} — Estimation Assumptions"
    c.fill      = _fill(DARK_BLUE)
    c.font      = _font(bold=True, color=WHITE, size=14)
    c.alignment = _align(h="left", v="center")
    ws.row_dimensions[1].height = 30

    # Subtitle
    ws.merge_cells("A2:D2")
    c = ws["A2"]
    c.value = "Generated by estimate-generator skill"
    c.fill      = _fill(MID_BLUE)
    c.font      = _font(color=WHITE, size=9, italic=True)
    c.alignment = _align(h="left", v="center")
    ws.row_dimensions[2].height = 16

    rows = [
        ("Project Parameters", None, None, True),
        ("Project Name",          cfg["project_name"],           "",    False),
        ("Sprint Length",         f"{cfg['sprint_length_days']} working days", "", False),
        ("Hours per Day",         f"{cfg['hours_per_day']} h",   "",    False),
        ("Overhead (Ceremonies)", f"{cfg['overhead_pct']}%",     "Standups, planning, retro, reviews", False),
        ("Contingency Buffer",    f"{cfg['contingency_pct']}%",  "Applied to raw PERT total", False),
        ("Project Start Date",    str(cfg.get("start_date", "TBD")), "", False),
        ("Team Composition", None, None, True),
    ]

    team = cfg.get("team", {})
    total_people = 0
    for role, count in team.items():
        rows.append((f"  {role} Developers", str(count), "", False))
        total_people += count
    rows.append(("  Total headcount", str(total_people), "", False))

    rows += [
        ("Capacity Model", None, None, True),
    ]

    gross = cfg["sprint_length_days"] * cfg["hours_per_day"]
    overhead_h = round(gross * cfg["overhead_pct"] / 100)
    effective  = gross - overhead_h
    usable     = round(effective * 0.90)
    team_cap   = usable * total_people

    rows += [
        ("Gross hours / person / sprint", f"{gross} h", "", False),
        ("Ceremony deduction",            f"{overhead_h} h", f"{cfg['overhead_pct']}% of gross", False),
        ("Effective hours / person / sprint", f"{effective} h", "", False),
        ("Usable hours / person / sprint",    f"{usable} h",    "90% of effective (10% sprint slack)", False),
        ("Total team capacity / sprint",      f"{team_cap} h",  f"{usable} h × {total_people} people", False),
    ]

    headers = ["Parameter", "Value", "Notes"]
    for col, h in enumerate(headers, start=1):
        c = ws.cell(row=3, column=col, value=h)
        style_header(c)
    ws.row_dimensions[3].height = 18

    row = 4
    for label, value, note, is_section in rows:
        if is_section:
            ws.merge_cells(f"A{row}:C{row}")
            c = ws.cell(row=row, column=1, value=label)
            c.fill      = _fill(LIGHT_BLUE)
            c.font      = _font(bold=True, color=DARK_BLUE, size=10)
            c.alignment = _align(h="left", v="center")
            c.border    = _border()
        else:
            bg = ALT_ROW if row % 2 == 0 else WHITE
            style_cell(ws.cell(row=row, column=1, value=label), bg=bg, bold=True)
            style_cell(ws.cell(row=row, column=2, value=value), bg=bg, align="center")
            style_cell(ws.cell(row=row, column=3, value=note),  bg=bg, italic=True,
                       color="666666")
        row += 1

    set_col_width(ws, 1, 38)
    set_col_width(ws, 2, 28)
    set_col_width(ws, 3, 50)

# ── Sheet 2: WBS + PERT ──────────────────────────────────────────

def build_wbs(wb, cfg):
    ws = wb.create_sheet("WBS + PERT")
    ws.sheet_view.showGridLines = False
    ws.freeze_panes = "A3"

    # Title row
    ws.merge_cells("A1:L1")
    c = ws["A1"]
    c.value = f"{cfg['project_name']} — Work Breakdown Structure + PERT Estimates"
    c.fill      = _fill(DARK_BLUE)
    c.font      = _font(bold=True, color=WHITE, size=13)
    c.alignment = _align(h="left", v="center")
    ws.row_dimensions[1].height = 28

    headers = ["Phase", "Work Package", "Task", "Assignee",
               "O (hrs)", "M (hrs)", "P (hrs)", "PERT (hrs)",
               "Variance", "Sprint", "Risk", "Notes"]
    for col, h in enumerate(headers, start=1):
        c = ws.cell(row=2, column=col, value=h)
        style_header(c)
    ws.row_dimensions[2].height = 18

    tasks = cfg.get("tasks", [])
    total_pert = 0.0
    total_var  = 0.0

    for i, t in enumerate(tasks):
        row = i + 3
        bg_risk = risk_color(t.get("risk", "Low"))
        bg_alt  = ALT_ROW if i % 2 == 0 else WHITE
        bg      = bg_risk  # colour rows by risk level for quick scanning

        o, m, p = t["O"], t["M"], t["P"]
        e = pert(o, m, p)
        v = variance(o, p)
        total_pert += e
        total_var  += v

        vals = [
            t.get("phase", ""),
            t.get("work_package", ""),
            t.get("task", ""),
            t.get("assignee", ""),
            o, m, p,
            e, round(v, 2),
            t.get("sprint", ""),
            t.get("risk", ""),
            t.get("notes", ""),
        ]
        aligns = ["left","left","left","center",
                  "center","center","center","center",
                  "center","center","center","left"]
        bolds  = [True, True, False, False,
                  False, False, False, True,
                  False, False, True, False]

        for col, (val, al, bo) in enumerate(zip(vals, aligns, bolds), start=1):
            c = ws.cell(row=row, column=col, value=val)
            style_cell(c, bg=bg, bold=bo, align=al,
                       wrap=(col == 3))  # wrap task description

    # Totals row — recompute locally for display (main() holds the canonical totals)
    local_pert = sum(pert(t["O"], t["M"], t["P"]) for t in tasks)
    local_var  = sum(variance(t["O"], t["P"]) for t in tasks)

    total_row = len(tasks) + 3
    ws.merge_cells(f"A{total_row}:G{total_row}")
    c = ws.cell(row=total_row, column=1, value="TOTAL (raw PERT)")
    c.fill      = _fill(MID_BLUE)
    c.font      = _font(bold=True, color=WHITE)
    c.alignment = _align(h="right")
    c.border    = _thick_bottom()

    c = ws.cell(row=total_row, column=8, value=round(local_pert, 1))
    c.fill      = _fill(MID_BLUE)
    c.font      = _font(bold=True, color=WHITE)
    c.alignment = _align(h="center")
    c.border    = _thick_bottom()

    c = ws.cell(row=total_row, column=9, value=round(local_var, 2))
    c.fill      = _fill(MID_BLUE)
    c.font      = _font(color=WHITE)
    c.alignment = _align(h="center")
    c.border    = _thick_bottom()

    # Column widths
    widths = [18, 22, 52, 12, 9, 9, 9, 11, 10, 9, 12, 30]
    for col, w in enumerate(widths, start=1):
        set_col_width(ws, col, w)

    ws.row_dimensions[1].height = 28
    for r in range(3, len(tasks) + 3):
        ws.row_dimensions[r].height = 20

