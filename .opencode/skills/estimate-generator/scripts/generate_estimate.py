VALID_SHEETS = {"assumptions", "wbs", "capacity", "sprint", "summary"}

def parse_sheets(sheets_arg: str) -> set:
    """Parse --sheets argument into a set of sheet names."""
    if sheets_arg.strip().lower() == "all":
        return set(VALID_SHEETS)
    requested = {s.strip().lower() for s in sheets_arg.split(",")}
    unknown = requested - VALID_SHEETS
    if unknown:
        print(f"ERROR: Unknown sheet name(s): {unknown}")
        print(f"       Valid names: {', '.join(sorted(VALID_SHEETS))}  or  'all'")
        sys.exit(1)
    return requested


def main():
    parser = argparse.ArgumentParser(
        description="Generate PERT-based project estimate Excel",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Sheet options (--sheets):
  wbs           Task breakdown + PERT estimates (default, always the core output)
  assumptions   Project parameters and team composition
  capacity      Per-role gross/ceremony/effective/usable hours
  sprint        Tasks grouped by sprint with milestone markers
  summary       PERT totals, contingency, sprint count, go-live date
  all           All five sheets

Examples:
  --sheets wbs                     # WBS only (quick estimate)
  --sheets wbs,summary             # WBS + totals and go-live date
  --sheets wbs,sprint              # WBS + sprint-by-sprint breakdown
  --sheets all                     # Full project pack
        """
    )
    parser.add_argument("--config",  required=True,
                        help="Path to estimate_config.json")
    parser.add_argument("--output",  required=True,
                        help="Output .xlsx file path")
    parser.add_argument("--sheets",  default="wbs",
                        help="Comma-separated sheet names or 'all' (default: wbs)")
    args = parser.parse_args()

    # ── Parse sheet selection ────────────────────────────────────
    sheets = parse_sheets(args.sheets)

    # ── Load config ──────────────────────────────────────────────
    try:
        with open(args.config, encoding="utf-8") as f:
            cfg = json.load(f)
    except FileNotFoundError:
        print(f"ERROR: Config file not found: {args.config}")
        sys.exit(1)
    except json.JSONDecodeError as e:
        print(f"ERROR: Invalid JSON in config file: {e}")
        sys.exit(1)

    # ── Validate required fields ─────────────────────────────────
    required = ["project_name", "sprint_length_days", "hours_per_day",
                "overhead_pct", "contingency_pct", "team", "tasks"]
    missing = [f for f in required if f not in cfg]
    if missing:
        print(f"ERROR: Missing required config fields: {missing}")
        sys.exit(1)

    # ── Pre-compute PERT data (always — lightweight, needed for totals) ──
    tasks_with_pert = []
    total_pert = 0.0
    total_var  = 0.0
    for t in cfg["tasks"]:
        tc        = dict(t)
        tc["_pert"] = pert(t["O"], t["M"], t["P"])
        total_pert += tc["_pert"]
        total_var  += variance(t["O"], t["P"])
        tasks_with_pert.append(tc)

    # ── Build workbook — only requested sheets ───────────────────
    wb = Workbook()
    built = []

    if "assumptions" in sheets:
        print("Building Assumptions sheet...")
        build_assumptions(wb, cfg)
        built.append("Assumptions")

    if "wbs" in sheets:
        print("Building WBS + PERT sheet...")
        build_wbs(wb, cfg)
        built.append("WBS + PERT")

    if "capacity" in sheets:
        print("Building Capacity Model sheet...")
        build_capacity(wb, cfg)
        built.append("Capacity Model")

    if "sprint" in sheets:
        print("Building Sprint Plan sheet...")
        build_sprint_plan(wb, cfg, tasks_with_pert)
        built.append("Sprint Plan")

    if "summary" in sheets:
        print("Building Summary sheet...")
        build_summary(wb, cfg, total_pert, total_var)
        built.append("Summary")

    if not built:
        print("ERROR: No sheets were built. Check your --sheets argument.")
        sys.exit(1)

    # Remove the blank default sheet if it wasn't used as the first sheet
    if wb.worksheets[0].title == "Sheet" and len(wb.worksheets) > 1:
        del wb["Sheet"]

    # Set tab colours (cycle through palette)
    tab_colors = ["1F3864", "2E75B6", "4472C4", "538135", "70AD47"]
    for i, sheet in enumerate(wb.worksheets):
        sheet.sheet_properties.tabColor = tab_colors[i % len(tab_colors)]

    # ── Save ─────────────────────────────────────────────────────
    try:
        wb.save(args.output)
        contingency = round(total_pert * cfg["contingency_pct"] / 100, 1)
        print(f"\nDone!  Saved to: {args.output}")
        print(f"  Sheets generated : {', '.join(built)}")
        print(f"  Total tasks      : {len(cfg['tasks'])}")
        print(f"  Raw PERT total   : {total_pert:.1f} h")
        print(f"  With {cfg['contingency_pct']}% buffer  : {total_pert + contingency:.1f} h")
    except PermissionError:
        print(f"ERROR: Cannot write to {args.output} — close the file if it is open in Excel.")
        sys.exit(1)

if __name__ == "__main__":
    main()
